import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'
const source=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const api=source('functions/api/ava-screening.ts')
const applicant=source('src/pages/AvaScreening.tsx')
const admin=source('src/pages/RecruitmentAdmin.tsx')
const access=source('functions/recruitment-admin/api.ts')
const db=source('db/submissions.sql')
const config=source('wrangler.jsonc')
const helper=source('functions/lib/avaOwnedIdentity.ts')

test('Owned identity is stored privately and uses one-time server challenges',()=>{
 assert.match(config,/"binding": "AVA_ID_BUCKET"/)
 assert.match(config,/operava-ava-identity-evidence/)
 assert.match(api,/action === 'identityStart'/)
 assert.match(api,/action === 'identitySubmit'/)
 assert.match(api,/crypto.randomUUID\(\)/)
 assert.match(api,/challenge_hash/)
 assert.match(api,/previous.expires_at<=now/)
 assert.match(api,/previous.submitted_at/)
 assert.match(api,/timingSafeEqualStr\(previous.challenge_hash,challengeHash\)/)
 assert.match(api,/identity_status='pending_review'/)
 assert.match(db,/CREATE TABLE IF NOT EXISTS ava_screening_owned_identity/)
 assert.match(helper,/OWNED_ID_TTL_MS=10\*60_000/)
 assert.match(helper,/validateCameraJpeg/)
})
test('All three camera frames require an explicit consent and visual inspection',()=>{
 assert.match(api,/form.get\('consent'\)!=='true'/)
 assert.match(api,/validateCameraJpeg\(form.get\('document'\)/)
 assert.match(api,/validateCameraJpeg\(form.get\('selfie'\)/)
 assert.match(api,/validateCameraJpeg\(form.get\('motion'\)/)
 assert.match(applicant,/getUserMedia/)
 assert.match(applicant,/identityConsent/)
 assert.match(applicant,/Capture turned selfie/)
 assert.match(applicant,/Submit identity for human verification/)
})
test('Human reviewer signs off only after inspecting captured evidence',()=>{
 assert.match(access,/accessIdentity\(request, env\)/)
 assert.match(api,/identityReviewChecksValid\(data\?\.checks\)/)
 assert.match(api,/note.length<12/)
 assert.match(api,/X-AVA-Reviewer-Identity/)
 assert.match(api,/manual_verified/)
 assert.match(helper,/faceVisuallyConsistent/)
 assert.match(helper,/motionReviewed/)
 assert.match(admin,/Approve manual identity review/)
 assert.match(admin,/Neutral selfie/)
 assert.match(admin,/Turned selfie/)
 assert.match(admin,/Required reviewer rationale/)
})
test('Identity approval does not fabricate scores or certified provider evidence',()=>{
 assert.match(api,/face_score=0,liveness_pass=0/)
 assert.match(api,/document_authentic=0,document_name_match=1,passport_nfc_pass=0/)
 assert.match(helper,/status==='verified'\|\|status==='manual_verified'/)
 assert.match(api,/identity_status!=='approved'/)
 assert.match(api,/AVA_ID_BUCKET\.put/)
 assert.match(api,/AVA_ID_BUCKET\.delete/)
 assert.doesNotMatch(applicant,/Email my secure phone verification link/)
})
