import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const ui=read('src/pages/AvaScreening.tsx')
const css=read('src/pages/AvaScreening.css')
const layout=read('src/site/Layout.tsx')
const initial=read('index.html')
test('AVA landing renders in light mode on first paint without overwriting website preference',()=>{
  assert.match(initial,/applicant-portal/)
  assert.match(initial,/ava \? 'light' : preferred/)
  assert.match(layout,/wasApplicantPortal/)
  assert.match(layout,/if \(!inApplicantPortal\)/)
  assert.match(layout,/operava-theme-change/)
})
test('Fixed outer document and active AVA pane prohibit vertical scrolling',()=>{
  assert.match(css,/#site-shell\.ava-screening-host\{[\s\S]*?position:fixed/)
  assert.match(css, /\.ava-assessment-deck\{[\s\S]*?overflow:hidden/)
  const final=css.slice(css.lastIndexOf('/* AVA compact white-first'))
  assert.match(final,/\.ava-workspace-body\{[\s\S]*?overflow:hidden!important/)
  assert.match(final,/\.ava-horizontal-scene\{[\s\S]*?overflow:hidden!important/)
  assert.match(final,/\.ava-scene-fit\{/)
  assert.match(ui,/content\.style\.zoom=String/)
  assert.match(ui,/ResizeObserver/)
  assert.match(ui,/MutationObserver/)
})
test('AVA records are paged horizontally rather than stacked to create scroll',()=>{
  assert.match(ui,/applications\.slice\(itemPage,itemPage\+1\)/)
  assert.match(ui,/documents\.slice\(itemPage,itemPage\+1\)/)
  assert.match(ui,/Next application/)
  assert.match(ui,/Next document/)
  assert.match(ui,/setItemPage\(0\)/)
})
test('AVA fills the viewport with one question board and no mascot sidecar',()=>{
  assert.ok(ui.includes('className="ava-assessment-deck"'))
  assert.ok(ui.includes('className="ava-ai-conversation"'))
  assert.ok(ui.includes('className="ava-ai-composer"'))
  assert.ok(ui.includes('className="ava-ai-message ava-ai-message--question"'))
  assert.ok(ui.includes('AVA · Instructions'))
  assert.ok(ui.includes('Submit & next question'))
  assert.ok(ui.includes('screen?.question?.prompt'))
  assert.ok(!ui.includes('ava-proctor-dock'))
  assert.ok(!ui.includes('ava-proctor-mermaid.svg'))
  assert.ok(!ui.includes('ava-proctor-character'))
  assert.ok(!css.includes('ava-proctor-dock'))
  assert.ok(!css.includes('ava-proctor-character'))
  assert.ok(!css.includes('ava-proctor-float'))
  assert.ok(css.includes('grid-template-columns:minmax(0,1fr);'))
  assert.match(css,/ava-board-question-enter/)
})
